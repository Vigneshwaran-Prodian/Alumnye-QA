"""Smart form filler. After 'Verify & join Alumnye' the app shows one or more profile screens. This module reads the
screen, works out what every input is (hint / label above it / input type), fills valid test values, taps the
forward button (Save & Finish / Continue / Next ...) and repeats until Home - with no per-screen scripting.
Deterministic: no AI is needed for the normal path."""
import random
import re
import time

from . import healer

# first match wins; (regex on the field's label/hint, value factory(person))
RULES = [
    (r"first\s*name|given\s*name|fname", lambda p: p["first"]),
    (r"last\s*name|sur\s*name|family\s*name|lname", lambda p: p["last"]),
    (r"full\s*name|^name$|your name|member name", lambda p: f"{p['first']} {p['last']}"),
    (r"e-?mail", lambda p: p["email"]),
    (r"mobile|phone|contact\s*(no|number)|whats\s*app", lambda p: p.get("mobile") or "9" + "".join(random.choice("0123456789") for _ in range(9))),
    (r"pin\s*code|zip|postal", lambda p: "600001"),
    (r"date of birth|dob|birth", lambda p: "01/01/1990"),
    (r"graduat|passing|batch|year", lambda p: "2015"),
    (r"company|employer|organi[sz]ation", lambda p: "Prodian Infotech"),
    (r"job\s*title|designation|role|position", lambda p: "QA Engineer"),
    (r"industry", lambda p: "Information Technology"),
    (r"institution|college|university|school", lambda p: "Anna University"),
    (r"degree|qualification", lambda p: "B.E."),
    (r"field of study|major|branch|department|course", lambda p: "Computer Science"),
    (r"city|town", lambda p: "Chennai"),
    (r"state|province", lambda p: "Tamil Nadu"),
    (r"country", lambda p: "India"),
    (r"address", lambda p: "12 Test Street"),
    (r"nominee|relation", lambda p: "Spouse"),
    (r"member\s*code", lambda p: None),            # auto-generated by the app: leave alone
    (r"bio|about|summary|description", lambda p: "QA automation test profile."),
    (r"linkedin|website|url|link", lambda p: "https://example.com/test"),
    (r"password", lambda p: "Test@12345"),
]
ACTIONS = ["Save & Finish", "Save and Finish", "Finish", "Save & Continue", "Join", "Continue",
           "Next", "Submit", "Save", "Done", "Get Started"]
SKIPPABLE = ["Skip", "Maybe later", "Not now", "Do this later"]


def label_for(nodes, n):
    """hint, else the nearest plain text just above the field (the visible label)."""
    if n.hint:
        return n.hint
    above = [m for m in nodes if m.label and not m.is_input and not m.clickable and 0 < n.cy - m.cy <= 160]
    if above:
        return min(above, key=lambda m: n.cy - m.cy).label
    return ""


def value_for(label, person, numeric=False):
    low = label.lower()
    for pat, fn in RULES:
        if re.search(pat, low):
            return fn(person)
    if numeric:
        return "10"
    return None if not label else f"Test {label[:20]}"


def plan_fill(nodes, person):
    """[(node, label, value)] for every EMPTY input on the screen; filled / auto fields are left alone."""
    plan = []
    for n in nodes:
        if not (n.is_input and n.enabled):
            continue
        if n.label.strip() and n.label.strip() != n.hint:        # already has a value (e.g. pre-filled email)
            continue
        label = label_for(nodes, n)
        val = value_for(label, person)
        if val:
            plan.append((n, label or f"field {n.ordinal}", val))
    return plan


def _pick_action(nodes):
    """Best forward button: (label, enabled, node). Only real controls count: a tappable element, or a DISABLED one
    (a disabled React Native button reports clickable=false). Headings / plain text never qualify."""
    for want in ACTIONS:
        for n in nodes:
            if not n.label or n.is_input or len(n.label) > 40 or want.lower() not in n.label.lower():
                continue
            if n.clickable or not n.enabled:
                return n.label, n.enabled, n
    return None, False, None


def type_into(app, n, val) -> bool:
    """Put `val` into the input described by snapshot node `n`. The field is found by what it IS (its hint or visible text), not by
    its position in a tree that may have changed since the snapshot; if no element can be found (slow device, re-render) the
    field is tapped by its on-screen position and typed into directly. Returns True when something was typed."""
    cands = []
    if n.hint:
        cands.append(f"xpath://{n.cls}[@hint={_xp(n.hint)}]")
    if n.label.strip() and n.label.strip() != n.hint:
        cands.append(f"xpath://{n.cls}[@text={_xp(n.label.strip())}]")
    cands.append(f"xpath:(//{n.cls})[{n.ordinal}]")
    el = app._try(cands, 2.5)
    if el is not None:
        el.click()
        app.enter_text(el, val)
        return True
    if not (n.cx and n.cy):
        return False
    app.tap_xy(n.cx, n.cy)                                      # same tap a person would make
    time.sleep(0.5)
    if app.platform == "android":
        app._adb("shell", "input", "text", val.replace(" ", "%s"))
        app.notes.append(f"form filler: typed into the field at x{n.cx},y{n.cy} by position (element lookup was too slow)")
        return True
    return False


def _xp(text):
    return "'" + text + "'" if "'" not in text else '"' + text + '"'


def fill_inputs(app, person) -> list:
    """Fill every empty input on the current screen. Several passes: a field that could not be filled in one pass (hidden by the
    keyboard, re-rendered, tap swallowed) is retried after the keyboard is closed and the screen re-read, instead of being skipped.
    A failure is written to the report, never swallowed. Returns [(label, value)]."""
    done, attempts = [], {}
    for _ in range(4):
        nodes = healer.snapshot(app.d.page_source, app.platform)
        plan = [p for p in plan_fill(nodes, person) if attempts.get((p[0].cls, p[0].ordinal), 0) < 2]
        if not plan:
            break
        for n, label, val in plan:
            key = (n.cls, n.ordinal)
            attempts[key] = attempts.get(key, 0) + 1
            try:
                if type_into(app, n, val):
                    done.append((label, val))
                    if re.search(r"mobile|phone", label.lower()):
                        person["mobile"] = val
                else:
                    app.notes.append(f"form filler: could not fill '{label}' on attempt {attempts[key]} (field not reachable)")
            except Exception as e:
                app.notes.append(f"form filler: could not fill '{label}' on attempt {attempts[key]} ({type(e).__name__})")
                continue
        app.dismiss_keyboard()
    return done


# messages that mean "this VALUE is wrong / taken" (a different value fixes it), as opposed to "this field is empty"
REJECT_RE = re.compile(r"already (registered|exists|in use|taken|used|linked)|is taken|not available|unavailable|duplicate|"
                       r"not valid|invalid|incorrect|must be|must contain|should be|too (short|long)|exceeds|cannot be|can't be", re.I)


def new_mobile(tried):
    """A fresh 10-digit Indian mobile (starts 6-9) that this run has not used for the field yet."""
    while True:
        v = random.choice("6789") + "".join(random.choice("0123456789") for _ in range(9))
        if v not in tried and len(set(v)) > 3:
            return v


def _nearest_input_above(nodes, err):
    cand = [n for n in nodes if n.is_input and 0 <= err.cy - n.cy <= 170]
    return min(cand, key=lambda n: err.cy - n.cy) if cand else None


def repair_validation(app, person, tried_values, log):
    """The app shows a validation message under a field (for example 'Phone number is already registered to another user').
    Read it, work out which field it belongs to, put a NEW value in that field and report what was understood.
    Known meanings are handled directly (a taken phone number -> a new number); anything else is interpreted by the AI.
    Returns True if a field was changed."""
    nodes = healer.snapshot(app.d.page_source, app.platform)
    errors = [n for n in nodes if n.label and not n.is_input and not n.clickable and len(n.label) <= 140 and REJECT_RE.search(n.label)]
    for err in errors:
        field = _nearest_input_above(nodes, err)
        if field is None or not field.enabled:
            continue                                                  # a disabled field (the pre-filled e-mail) cannot be changed
        label = label_for(nodes, field) or err.label
        current = field.label.strip() if field.label.strip() != field.hint else ""
        kind_phone = re.search(r"mobile|phone|contact|number", f"{label} {err.label}", re.I)
        tried = tried_values.setdefault(label, [])
        if current and current not in tried:
            tried.append(current)
        if len(tried) > 5:
            continue                                                  # bounded: never loop forever on one field
        how = "known rule"
        if kind_phone:
            new = new_mobile(tried)
            meaning = "the phone number is already used by someone else, so a different number is needed"
        else:
            if not app.cfg["ai"]["enabled"]:
                continue
            try:
                from . import qwen
                app.ai_calls += 1
                ans = qwen.ask_fix(app.cfg, label, current, err.label, tried)
                qwen.log_usage(app.run_id, app.scenario, f"validation '{err.label}' on '{label}'", f"AI suggested a new value ({ans.get('understood', '')})")
            except Exception as e:
                log.append(f"AI could not interpret '{err.label}': {e}")
                continue
            new, meaning, how = ans["value"], ans.get("understood", ""), "AI"
            if not new or new == current or new in tried:
                continue
        el = app._try([f"xpath:(//{field.cls})[{field.ordinal}]"], 1.5)
        if el is None:
            continue
        el.click()
        try:
            el.clear()
        except Exception:
            pass
        app.enter_text(el, new)
        app.dismiss_keyboard()
        tried.append(new)
        if kind_phone:
            person["mobile"] = new
        app.events.append({"tier": "validation", "key": label, "strategy": f"retyped {label}", "reason": f"{err.label} -> {meaning}"})
        app.notes.append(f"validation '{err.label}' on '{label}': {meaning}; entered a new value {new} ({how})")
        log.append(f"validation '{err.label}' -> new {label} {new} ({how})")
        print(f"    [validation] '{err.label}' -> {meaning}; trying {new} ({how})")
        end = time.time() + 3.5                                       # the app re-validates: wait for the old message to go
        while time.time() < end and err.label in app.labels():
            time.sleep(0.3)
        return True
    return False


def _sig(app):
    return hash(tuple(app.labels()))


GOAL = "finish this profile screen (fill every required field marked * with a valid value) and move forward until the Home screen"


def complete_profile(app, person, max_screens=8) -> list:
    tried_values = {}
    """Run the post-verification screens until Home. Deterministic first; if it cannot make progress the local Qwen
    is asked for the next single action (tap / type / scroll), the runner performs it, and the loop carries on."""
    log = []
    for screen in range(1, max_screens + 1):
        if app.at_home(1):
            break
        sig0 = _sig(app)
        filled = fill_inputs(app, person)
        log += [f"screen {screen}: {l} = {v}" for l, v in filled]

        nodes = healer.snapshot(app.d.page_source, app.platform)
        label, enabled, node = _pick_action(nodes)
        advanced, tried = False, []
        if label and enabled:
            app.tap_label(label)
            log.append(f"screen {screen}: tapped '{label}'")
            tried.append(f"tapped '{label}'")
            app.watch_messages(f"profile screen {screen}: tapped '{label}'", app.mark(), seconds=2.0)
            advanced = app.at_home(1) or _sig(app) != sig0
        elif label is None and not any(n.is_input for n in nodes):
            skip = next((s for s in SKIPPABLE if app._try([f"btnx:{s}"], 0.5)), None)
            if skip:
                app.tap_label(skip)
                log.append(f"screen {screen}: tapped '{skip}'")
                advanced = True
        elif label and not enabled:
            tried.append(f"'{label}' is disabled (a required field is probably empty or invalid)")

        repairs = 0
        while not advanced and repairs < 5 and repair_validation(app, person, tried_values, log):   # read the error, change the value, try again
            repairs += 1
            nodes = healer.snapshot(app.d.page_source, app.platform)
            label, enabled, node = _pick_action(nodes)
            if label and enabled:
                app.tap_label(label)
                log.append(f"screen {screen}: tapped '{label}' after correcting a rejected value")
                app.watch_messages(f"profile screen {screen}: tapped '{label}' after a correction", app.mark(), seconds=2.0)
                advanced = app.at_home(1) or _sig(app) != sig0

        if not advanced:                                  # deterministic path is stuck: let Qwen steer, bounded
            ok = app.unstick(GOAL, lambda: app.at_home(1) or _sig(app) != sig0, tried, turns=3)
            log.append(f"screen {screen}: Qwen-assisted ({'progressed' if ok else 'could not progress'})")
            if not ok:
                hints = [n.label for n in nodes if n.label and re.search(r"required|invalid|enter|select|must|please", n.label, re.I)]
                app.soft_check(False, f"profile screen {screen}: could not move forward (tried: {'; '.join(tried) or 'nothing'}"
                                      f"; Qwen could not unblock it; visible hints: {'; '.join(hints[:4]) or 'none'})")
                break
    app.notes.append("Profile form filled automatically: " + ("; ".join(log) if log else "nothing to fill"))
    return log
